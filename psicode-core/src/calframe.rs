    /// Псевдослучайные клетки payload (как реальный L3-кадр).
    fn random_cells(bpc: u32, seed: u64) -> Vec<u8> {
        let mask: u16 = if bpc >= 16 { u16::MAX } else { (1u16 << bpc) - 1 };
        let mut rng = XorShift64(seed | 1);
        (0..PAYLOAD_COLS * PAYLOAD_ROWS)
            .map(|_| ((rng.next_u64() >> 24) as u16 & mask) as u8)
            .collect()
    }

    /// Запас детекции маркера: на КАЛИБРОВОЧНОМ кадре ρ высоко и U≈1 при всех
    /// исследованных блюрах и шумах, на PAYLOAD-кадре оба признака далеко ниже
    /// порога. Печатает измеренные величины (это и есть заявленный запас).
    #[test]
    fn marker_detection_margin_under_blur_and_noise() {
        let p = prof(12);
        let map = |u: f64, v: f64| (u, v);
        let mut worst_cal_rho = f64::INFINITY;
        let mut worst_cal_u = f64::INFINITY;
        let mut best_pay_rho: f64 = 0.0;
        let mut best_pay_u = f64::NEG_INFINITY;

        // Углы развёртки; полная сетка — в `psicode-core/examples/calib_ab.rs`.
        for &sl in &[1.0f64, 4.0] {
            for &noise in &[1.79f64, 8.0] {
                let ch = measured_channel(sl, (3.0 * sl).max(6.0), noise);
                // калибровочный кадр
                let fr = render_calibration_frame(&p, 0);
                let size = fr.size_px;
                let s = sampler(apply_channel(&fr.rgb, size, &ch), size);
                let rho = marker_score(&p, &map, &s);
                let u = tile_uniformity(&p, &map, &s);
                println!("calib σl={sl} noise={noise}: ρ={rho:.4} U={u:.4}");
                worst_cal_rho = worst_cal_rho.min(rho);
                worst_cal_u = worst_cal_u.min(u);
                assert!(rho >= MARKER_RHO_MIN, "маркер не найден: ρ={rho} (σl={sl}, шум={noise})");
                assert!(u >= UNIFORMITY_MIN, "однородность мала: U={u}");
                assert!(is_calibration_frame(&p, &map, &s));

                // payload-кадр того же профиля через тот же канал
                for seed in [1u64, 2] {
                    let cells = random_cells(symbol::bits_per_cell(&p), seed);
                    let pf = symbol::render_symbol_counter(&p, &cells, 7);
                    let ps = sampler(apply_channel(&pf.rgb, pf.size_px, &ch), pf.size_px);
                    let prho = marker_score(&p, &map, &ps);
                    let pu = tile_uniformity(&p, &map, &ps);
                    best_pay_rho = best_pay_rho.max(prho.abs());
                    best_pay_u = best_pay_u.max(pu);
                    assert!(
                        !is_calibration_frame(&p, &map, &ps),
                        "ЛОЖНОЕ срабатывание на payload: ρ={prho:.3} U={pu:.3}"
                    );
                }
            }
        }
        println!(
            "ЗАПАС маркера: калибровка ρ≥{worst_cal_rho:.3} U≥{worst_cal_u:.3} | \
             payload |ρ|≤{best_pay_rho:.3} U≤{best_pay_u:.3} | пороги {MARKER_RHO_MIN}/{UNIFORMITY_MIN}"
        );
        assert!(worst_cal_rho - best_pay_rho > 0.3, "запас по ρ мал");
    }

