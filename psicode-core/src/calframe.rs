    // Синтетический канал: гамма -> luma-блюр + ХРОМА-НЧ (ISP) -> смешивание
    // каналов -> gain/offset -> шум. Хрома-НЧ и есть то, что убивает
    // односкеточную референсную строку §3.4.
    // -----------------------------------------------------------------------

    pub(super) struct XorShift64(pub u64);
    impl XorShift64 {
        fn next_u64(&mut self) -> u64 {
            let mut x = self.0;
            x ^= x << 13;
            x ^= x >> 7;
            x ^= x << 17;
            self.0 = x;
            x
        }
        fn next_f64(&mut self) -> f64 {
            ((self.next_u64() >> 11) as f64 + 1.0) / (1u64 << 53) as f64
        }
        fn next_gauss(&mut self) -> f64 {
            let u1 = self.next_f64();
            let u2 = self.next_f64();
            (-2.0 * u1.ln()).sqrt() * (core::f64::consts::TAU * u2).cos()
        }
    }

    #[derive(Clone, Copy)]
    pub(super) struct Chan {
        /// Гамма дисплея (drive -> линейный свет), на канал.
        pub gamma: [f64; 3],
        /// σ блюра ЯРКОСТИ, display-px.
        pub sigma_luma: f64,
        /// σ НЧ-фильтра ХРОМЫ ISP, display-px (то, что ломает §3.4).
        pub sigma_chroma: f64,
        /// Матрица смешивания каналов (сенсор+CCM), уже с усилениями.
        pub mix: [[f64; 3]; 3],
        /// Аддитивная вуаль на канал.
        pub off: [f64; 3],
        /// Мультипликативное поле освещённости: от центра к краю.
        pub field: (f64, f64),
        /// σ шума в градациях 0..255 (на отсчёт пикселя).
        pub noise: f64,
        pub seed: u64,
    }

    /// «Истинная» матрица развязки: `s = A·t + off` => `t = A⁻¹s − A⁻¹off`.
    pub(super) fn truth_matrix(ch: &Chan) -> ChannelMatrix {
        let a = ch.mix;
        let det = a[0][0] * (a[1][1] * a[2][2] - a[1][2] * a[2][1])
            - a[0][1] * (a[1][0] * a[2][2] - a[1][2] * a[2][0])
            + a[0][2] * (a[1][0] * a[2][1] - a[1][1] * a[2][0]);
        let mut n = [[0.0f64; 3]; 3];
        for i in 0..3 {
            for j in 0..3 {
                let (r0, r1) = ((j + 1) % 3, (j + 2) % 3);
                let (c0, c1) = ((i + 1) % 3, (i + 2) % 3);
                n[i][j] = (a[r0][c0] * a[r1][c1] - a[r0][c1] * a[r1][c0]) / det;
            }
        }
        let mut q = [0.0f64; 3];
        for i in 0..3 {
            for j in 0..3 {
                q[i] -= n[i][j] * ch.off[j];
            }
        }
        ChannelMatrix { n, q }
    }

    fn blur(src: &[f64], w: usize, h: usize, sigma: f64) -> Vec<f64> {
        if sigma <= 0.0 {
            return src.to_vec();
        }
        let r = (3.0 * sigma).ceil().min(20.0) as isize;
        let mut kern = vec![0.0f64; (2 * r + 1) as usize];
        let mut ks = 0.0;
        for (j, kv) in kern.iter_mut().enumerate() {
            let d = j as isize - r;
            *kv = (-(d * d) as f64 / (2.0 * sigma * sigma)).exp();
            ks += *kv;
        }
        for kv in kern.iter_mut() {
            *kv /= ks;
        }
        let cx = |v: isize, n: usize| v.clamp(0, n as isize - 1) as usize;
        let mut tmp = vec![0.0f64; w * h];
        for y in 0..h {
            for x in 0..w {
                let mut acc = 0.0;
                for (j, &kv) in kern.iter().enumerate() {
                    acc += kv * src[y * w + cx(x as isize + j as isize - r, w)];
                }
                tmp[y * w + x] = acc;
            }
        }
        let mut dst = vec![0.0f64; w * h];
        for y in 0..h {
            for x in 0..w {
                let mut acc = 0.0;
                for (j, &kv) in kern.iter().enumerate() {
                    acc += kv * tmp[cx(y as isize + j as isize - r, h) * w + x];
                }
                dst[y * w + x] = acc;
            }
        }
        dst
    }

    /// Прогоняет drive-кадр через канал, возвращает СЫРОЙ (после обратной
    /// гаммы камеры) нормированный RGB-буфер снимка.
    pub(super) fn apply_channel(rgb: &[[u8; 3]], size: usize, ch: &Chan) -> Vec<[f32; 3]> {
        let n = size * size;
        // 1. линеаризация дисплея
        let mut lin = [vec![0.0f64; n], vec![0.0f64; n], vec![0.0f64; n]];
        for i in 0..n {
            for c in 0..3 {
                lin[c][i] = (rgb[i][c] as f64 / 255.0).powf(ch.gamma[c]);
            }
        }
        // 2. Y / Cb / Cr: яркость блюрится слабо, хрома — сильно (модель ISP)
        let mut y = vec![0.0f64; n];
        let mut cb = vec![0.0f64; n];
        let mut cr = vec![0.0f64; n];
        for i in 0..n {
            y[i] = 0.299 * lin[0][i] + 0.587 * lin[1][i] + 0.114 * lin[2][i];
            cb[i] = lin[2][i] - y[i];
            cr[i] = lin[0][i] - y[i];
        }
        let y = blur(&y, size, size, ch.sigma_luma);
        let cb = blur(&cb, size, size, ch.sigma_chroma);
        let cr = blur(&cr, size, size, ch.sigma_chroma);
        for i in 0..n {
            let r = y[i] + cr[i];
            let b = y[i] + cb[i];
            let g = (y[i] - 0.299 * r - 0.114 * b) / 0.587;
            lin[0][i] = r;
            lin[1][i] = g;
            lin[2][i] = b;
        }
        // 3. поле освещённости (мультипликативное, радиальное)
        let (f0, f1) = ch.field;
        let cxy = (size as f64 - 1.0) / 2.0;
        let rmax = (2.0f64).sqrt() * cxy;
        // 4. смешивание каналов + вуаль + шум + обратная гамма камеры
        let mut rng = XorShift64(ch.seed | 1);
        let noise = ch.noise / 255.0;
        let mut out = vec![[0.0f32; 3]; n];
        for i in 0..n {
            let (px, py) = ((i % size) as f64, (i / size) as f64);
            let rr = ((px - cxy).powi(2) + (py - cxy).powi(2)).sqrt() / rmax;
            let f = f0 + (f1 - f0) * rr;
            let t = [lin[0][i] * f, lin[1][i] * f, lin[2][i] * f];
            for c in 0..3 {
                let mut v = ch.off[c];
                for j in 0..3 {
                    v += ch.mix[c][j] * t[j];
                }
                v += noise * rng.next_gauss();
                // камера отдаёт СЫРОЙ код: s_raw = v^(1/γ_cam), γ_cam = 2.2
                out[i][c] = v.max(0.0).powf(1.0 / 2.2) as f32;
            }
        }
        out
    }

    pub(super) fn sampler(buf: Vec<[f32; 3]>, size: usize) -> impl Fn(f64, f64) -> [f32; 3] {
        move |x: f64, y: f64| {
            let xi = (x.round() as isize).clamp(0, size as isize - 1) as usize;
            let yi = (y.round() as isize).clamp(0, size as isize - 1) as usize;
            buf[yi * size + xi]
        }
    }

    /// Канал, максимально близкий к ЗАМЕРЕННОМУ: кросстолк до −0.26 (B->G на
    /// Galaxy A22), поле 0.86 -> 0.62 по кадру, шум 1.79 кода на клетку.
    pub(super) fn measured_channel(sigma_luma: f64, sigma_chroma: f64, noise: f64) -> Chan {
        Chan {
            gamma: [2.2, 2.2, 2.25],
            sigma_luma,
            sigma_chroma,
            // Смешивание — СПЕКТРАЛЬНОЕ ПЕРЕКРЫТИЕ сенсора, поэтому матрица
            // НЕОТРИЦАТЕЛЬНА (её обратная — та самая CCM с отрицательными
            // членами, замеренная как «кросстолк до −0.26 B->G»). Модель с
            // отрицательными членами В ПРЯМОМ направлении физична только вместе
            // с клиппингом ISP, а клиппинг ломает ЛЮБУЮ линейную оценку — и
            // референсную строку, и калибровочный кадр одинаково, — то есть
            // маскирует сравниваемый эффект вместо того, чтобы его показать.
            mix: [
                [0.95, 0.20, 0.02],
                [0.05, 1.00, 0.26],
                [0.01, 0.08, 0.90],
            ],
            off: [0.012, 0.010, 0.015],
            field: (0.86, 0.62),
            noise,
            seed: 0x51_C0_DE_00_11_22_33_44,
        }
    }

