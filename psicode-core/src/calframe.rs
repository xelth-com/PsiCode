/// Класс плитки по индексу орбиты `min(slot, 23 − slot)`.
///
/// Порядок НЕ произволен. Орбиты отличаются РАДИУСОМ от центра кадра, а
/// виньетирование — чётная функция радиуса, которую точечная симметрия НЕ
/// снимает (она снимает нечётную часть). Поэтому:
///
/// * **нейтральная лесенка** `K, g1, g3, W` сидит на ОДНОМ радиусе (орбиты 5,
///   6, 8, 11 — квадрат радиуса 2.5 в единицах шага сетки), и только средняя
///   ступень `g2` вынесена в центр. Якоря лесенки (K и W) при этом видят
///   ОДИНАКОВОЕ поле, и оценка гаммы не смещается разностью освещённости;
/// * **цветные патчи** намеренно разбросаны по радиусам (R 8.5, G/B 6.5,
///   C/M 4.5, Y 0.5) — им нужна пространственная РАЗНОСТЬ, иначе полином поля
///   [`FIELD_TERMS`] нечем определить;
/// * **зонд блюра** — в угловой орбите: его наблюдаемая (контраст) от поля не
///   зависит вовсе, значит самое «плохое» по освещённости место достаётся
///   единственному классу, которому всё равно.
const SLOT_CLASS: [usize; CLASSES] = [
    CLASS_R,    // орбита 0: (0,0)/(5,3), r² 8.5
    CLASS_G,    // орбита 1: (0,1)/(5,2), r² 6.5
    CLASS_B,    // орбита 2: (0,2)/(5,1), r² 6.5
    CLASS_BLUR, // орбита 3: (0,3)/(5,0), r² 8.5 — поле безразлично
    CLASS_C,    // орбита 4: (1,0)/(4,3), r² 4.5
    CLASS_K,    // орбита 5: (1,1)/(4,2), r² 2.5 — якорь лесенки
    CLASS_G1,   // орбита 6: (1,2)/(4,1), r² 2.5
    CLASS_M,    // орбита 7: (1,3)/(4,0), r² 4.5
    CLASS_G3,   // орбита 8: (2,0)/(3,3), r² 2.5
    CLASS_Y,    // орбита 9: (2,1)/(3,2), r² 0.5
    CLASS_G2,   // орбита 10: (2,2)/(3,1), r² 0.5
    CLASS_W,    // орбита 11: (2,3)/(3,0), r² 2.5 — якорь лесенки
];

/// Точечно-симметричный партнёр слота (поворот сетки плиток на 180°).
#[inline]
pub fn partner_slot(slot: usize) -> usize {
    TILES - 1 - slot.min(TILES - 1)
}

/// Класс патча в слоте.
#[inline]
pub fn slot_class(slot: usize) -> usize {
    let s = slot.min(TILES - 1);
    SLOT_CLASS[s.min(partner_slot(s))]
}

/// Первый (верхний) слот класса. Второй — [`partner_slot`] от него.
pub fn class_slot(class: usize) -> usize {
    SLOT_CLASS.iter().position(|&c| c == class).unwrap_or(0)
}

/// Граница `i`-й плитки при делении `n` клеток на `k` частей, СИММЕТРИЧНО:
/// `edge(i) + edge(k − i) = n` тождественно (округление к ближайшему, вверх при
/// половине). Именно это делает пары слотов точечно-симметричными, а значит —
/// линейное поле освещённости сокращающимся ТОЧНО.
#[inline]
fn edge(i: usize, n: usize, k: usize) -> usize {
    (2 * i * n + k) / (2 * k)
}

fn shrink(a: usize, z: usize, guard: usize) -> (usize, usize) {
    let w = z.saturating_sub(a);
    if w < 3 {
        return (a, 0);
    }
    let g = guard.min((w - 1) / 2);
    (a + g, w - 2 * g)
}

/// Прямоугольник ТЕЛА плитки в payload-клетках: `(pc0, pr0, cols, rows)`, ров
/// уже снят. Плитки нумеруются построчно, `slot = tr·TILE_COLS + tc`.
pub fn tile_rect(slot: usize) -> (usize, usize, usize, usize) {
    let slot = slot.min(TILES - 1);
    let (tr, tc) = (slot / TILE_COLS, slot % TILE_COLS);
    let c0 = edge(tc, GRID_COLS, TILE_COLS);
    let c1 = edge(tc + 1, GRID_COLS, TILE_COLS);
    let r0 = MARKER_ROWS + edge(tr, BAND_ROWS, TILE_ROWS);
    let r1 = MARKER_ROWS + edge(tr + 1, BAND_ROWS, TILE_ROWS);
    let (pc0, cols) = shrink(c0, c1, GUARD_COLS);
    let (pr0, rows) = shrink(r0, r1, GUARD_ROWS);
    (pc0, pr0, cols, rows)
}

/// Измеряемая (внутренняя) часть плитки: тело с отступом [`READ_MARGIN`].
pub fn tile_read_rect(slot: usize) -> (usize, usize, usize, usize) {
    let (c0, r0, cw, rh) = tile_rect(slot);
    if cw == 0 || rh == 0 {
        return (c0, r0, 0, 0);
    }
    let mc = READ_MARGIN.min((cw - 1) / 2);
    let mr = READ_MARGIN.min((rh - 1) / 2);
    (c0 + mc, r0 + mr, cw - 2 * mc, rh - 2 * mr)
}

/// Drive-цвет сплошного класса. `None` — класс не сплошной (зонд блюра).
pub fn class_drive(class: usize, k: u8, w: u8) -> Option<[u8; 3]> {
    let grey = |f: f64| -> u8 {
        (k as f64 + (w as f64 - k as f64) * f)
            .round()
            .clamp(0.0, 255.0) as u8
    };
    Some(match class {
        CLASS_K => [k, k, k],
        CLASS_W => [w, w, w],
        CLASS_R => [w, k, k],
        CLASS_G => [k, w, k],
        CLASS_B => [k, k, w],
        CLASS_C => [k, w, w],
        CLASS_M => [w, k, w],
        CLASS_Y => [w, w, k],
        CLASS_G1 => [grey(0.25); 3],
        CLASS_G2 => [grey(0.5); 3],
        CLASS_G3 => [grey(0.75); 3],
        _ => return None,
    })
}

/// Шаги решётки зонда блюра в display-px, от грубого к мелкому. Заданы В
/// КЛЕТКАХ (2, 1, ½), поэтому относительная точность геометрии одинакова при
/// любом `cell_size_px`, а σ выдаётся в display-px и прямо сравним с `cell`.
pub fn blur_pitches(cell: usize) -> [usize; 3] {
    [(2 * cell).max(4), cell.max(3), (cell / 2).max(2)]
}

/// `true` = белый штрих решётки зонда блюра в точке `(xr, yr)` тела плитки
/// (px от левого верхнего угла тела, размер тела `bw × bh`).
/// `orient_x = true` — штрихи вертикальные (модуляция по X, меряет σx).
fn blur_white(orient_x: bool, xr: usize, yr: usize, bw: usize, bh: usize, cell: usize) -> bool {
    let p = blur_pitches(cell);
    if orient_x {
        let band = (yr * 3 / bh.max(1)).min(2);
        (xr % p[band]) >= p[band] / 2
    } else {
        let band = (xr * 3 / bw.max(1)).min(2);
        (yr % p[band]) >= p[band] / 2
    }
}

/// Ориентация зонда блюра в слоте: верхняя копия — X, нижняя — Y.
///
/// Строгая точечная симметрия ЗДЕСЬ не нужна: наблюдаемая зонда — ОТНОШЕНИЕ
/// (контраст Мишельсона), поле в нём сокращается и без усреднения пары. Зато
/// каждая ориентация получает всю плитку целиком, а не половину, что даёт по
/// 4–5 полных периодов даже на грубом шаге.
#[inline]
pub fn blur_orient_x(slot: usize) -> bool {
    slot < TILES / 2
}

