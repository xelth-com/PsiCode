/// Диагностика раскладки: размеры тела и измеряемой части плиток в display-px
/// при данном `cell`. `(мин. тело X, мин. тело Y, мин. измеряемая X,
/// мин. измеряемая Y, зазор до чужого цвета X, зазор Y)`.
pub fn layout_metrics(cell: usize) -> (usize, usize, usize, usize, usize, usize) {
    let mut bw = usize::MAX;
    let mut bh = usize::MAX;
    let mut rw = usize::MAX;
    let mut rh = usize::MAX;
    for slot in 0..TILES {
        let (_, _, cw, ch) = tile_rect(slot);
        let (_, _, mw, mh) = tile_read_rect(slot);
        bw = bw.min(cw);
        bh = bh.min(ch);
        rw = rw.min(mw);
        rh = rh.min(mh);
    }
    (
        bw * cell,
        bh * cell,
        rw * cell,
        rh * cell,
        (GUARD_COLS + READ_MARGIN) * cell,
        (GUARD_ROWS + READ_MARGIN) * cell,
    )
}

