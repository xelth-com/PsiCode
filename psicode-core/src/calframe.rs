/// Установившийся период калибровочных кадров.
pub const CALIB_PERIOD: u64 = 128;

/// Расписание с УДВОЕНИЕМ: 0, 1, 2, 4, 8, 16, 32, 64, 128, далее каждые 128.
///
/// Свойство удвоения: подключившись на кадре `t ∈ (2^j, 2^{j+1}]`, приёмник
/// ждёт до кадра `2^{j+1} ≤ 2t`, то есть не дольше удвоенного «возраста»
/// передачи. В установившемся режиме худшее ожидание — 127 кадров.
pub fn is_calibration_index(i: u64) -> bool {
    if i < CALIB_PERIOD {
        i == 0 || i.is_power_of_two()
    } else {
        i % CALIB_PERIOD == 0
    }
}

/// Сколько калибровочных кадров в `[0, i)`.
pub fn calibration_count_before(i: u64) -> u64 {
    if i == 0 {
        return 0;
    }
    // малые: 0, 1, 2, 4, ..., 64
    let mut small = 0u64;
    for c in [0u64, 1, 2, 4, 8, 16, 32, 64] {
        if c < i {
            small += 1;
        }
    }
    let big = if i > CALIB_PERIOD {
        (i - 1) / CALIB_PERIOD
    } else {
        0
    };
    small + big
}

/// Ближайший калибровочный кадр СТРОГО после `i`.
pub fn next_calibration_index(i: u64) -> u64 {
    let mut j = i + 1;
    // не более CALIB_PERIOD шагов до попадания
    while !is_calibration_index(j) {
        j += 1;
    }
    j
}

/// Ожидание приёмника, подключившегося НА кадре `i`, в кадрах: 0, если этот
/// кадр сам калибровочный, иначе расстояние до следующего.
pub fn join_wait(i: u64) -> u64 {
    if is_calibration_index(i) {
        0
    } else {
        next_calibration_index(i) - i
    }
}

/// Худшее ожидание подключившегося приёмника среди стартов в `[0, n)`, кадров.
pub fn worst_join_wait(n: u64) -> u64 {
    (0..n).map(join_wait).max().unwrap_or(0)
}

/// Доля калибровочных кадров среди первых `n` кадров потока.
pub fn schedule_overhead(n: u64) -> f64 {
    if n == 0 {
        return 0.0;
    }
    calibration_count_before(n) as f64 / n as f64
}

