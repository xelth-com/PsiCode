/// Калибровка канала, снятая с одного калибровочного кадра (§4-IB.4).
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct CalibEstimate {
    /// Матрица развязки §3.4 `t̂ = N·s + q` по ВСЕМ 24 плиткам (поле снято
    /// усреднением точечно-симметричных пар).
    pub matrix: ChannelMatrix,
    /// Пер-канальная гамма ЛИНЕАРИЗАЦИИ (показатель для сырого отсчёта).
    pub gammas: [f64; 3],
    /// σ блюра по X, display-px плоскости кадра.
    pub sigma_x_px: f64,
    /// σ блюра по Y, display-px.
    pub sigma_y_px: f64,
    /// σ блюра, изотропная сводка `sqrt((σx²+σy²)/2)`, display-px.
    pub sigma_px: f64,
    /// СКО невязки матричного фита по классам (в единицах линейного drive).
    pub residual: f64,
    /// Расхождение матриц, снятых по верхней и нижней половине кадра —
    /// ПРОСТРАНСТВЕННАЯ изменчивость канала (ошибка формы, [`ChannelMatrix::shape_rel_error`]).
    pub spatial_spread: f64,
    /// Минимум оценённого поля освещённости по плиткам (нормировано к среднему 1).
    pub field_lo: f64,
    /// Максимум оценённого поля освещённости по плиткам.
    pub field_hi: f64,
    /// Корреляция маркера.
    pub marker_rho: f64,
    /// Однородность плиток.
    pub uniformity: f64,
    /// Ядро МЕЖКЛЕТОЧНОЙ ИНТЕРФЕРЕНЦИИ на канал ([`crate::isi`]), снятое с
    /// этого же кадра.
    ///
    /// Место здесь ровно то же, что у матрицы 3×3: ядро — свойство связки
    /// «дисплей + оптика + ISP», а не кадра. Замер: по 23 снимкам СТАТИЧНОГО
    /// символа медианное отклонение отсчёта равно 0.0006 при силе ядра 0.053, а
    /// на цветном наборе КЭШИРОВАННОЕ медианное ядро обгоняет покадровую оценку
    /// (30/32 против 28/32 выживших страйпов, SER 0.00018 против 0.00046) и
    /// стоит +1.05 мс вместо +3.0 мс на кадр.
    ///
    /// `None` — на этом кадре ядро оценить не удалось.
    pub isi: Option<[IsiKernel; 3]>,
    /// Оценка получилась (система не вырождена).
    pub ok: bool,
}

impl CalibEstimate {
    /// Вырожденная («ничего не измерено») оценка.
    pub fn degenerate() -> Self {
        CalibEstimate {
            matrix: ChannelMatrix::identity(),
            gammas: [tone::DEFAULT_GAMMA; 3],
            sigma_x_px: 0.0,
            sigma_y_px: 0.0,
            sigma_px: 0.0,
            residual: f64::INFINITY,
            spatial_spread: f64::INFINITY,
            field_lo: 1.0,
            field_hi: 1.0,
            marker_rho: 0.0,
            uniformity: 0.0,
            isi: None,
            ok: false,
        }
    }
}

/// Средние сырые RGB по ИЗМЕРЯЕМОЙ части каждой плитки.
fn tile_means(
    p: &CalibProfile,
    map: &dyn Fn(f64, f64) -> (f64, f64),
    sample: &dyn Fn(f64, f64) -> [f32; 3],
) -> [[f64; 3]; TILES] {
    let mut out = [[0.0f64; 3]; TILES];
    for (slot, o) in out.iter_mut().enumerate() {
        let (c0, r0, cw, rh) = tile_read_rect(slot);
        if cw == 0 || rh == 0 {
            continue;
        }
        let mut acc = [0.0f64; 3];
        let mut cnt = 0.0f64;
        for pr in r0..r0 + rh {
            for pc in c0..c0 + cw {
                let s = cell_rgb(p, pc, pr, map, sample);
                for c in 0..3 {
                    acc[c] += s[c];
                }
                cnt += 1.0;
            }
        }
        if cnt > 0.0 {
            for c in 0..3 {
                o[c] = acc[c] / cnt;
            }
        }
    }
    out
}

/// Центр плитки в нормированных координатах кадра, примерно `[-1, 1]²`.
pub fn tile_centre_norm(slot: usize) -> (f64, f64) {
    let (c0, r0, cw, rh) = tile_rect(slot);
    let cx = c0 as f64 + cw as f64 / 2.0;
    let cy = r0 as f64 + rh as f64 / 2.0;
    let hx = PAYLOAD_COLS as f64 / 2.0;
    let hy = PAYLOAD_ROWS as f64 / 2.0;
    ((cx - hx) / hx, (cy - hy) / hy)
}

/// Членов модели поля освещённости: `1, x, y, x², y², xy` (био-квадратика) —
/// сглаживатель поверх ПРЯМЫХ поклеточных замеров поля по рву.
///
/// Зачем поле вообще снимается ЗДЕСЬ, если покадрово оно берётся из данных:
/// плитки классов физически стоят в РАЗНЫХ местах кадра, а виньетирование —
/// ЧЁТНАЯ функция радиуса, и точечно-симметричная пара её НЕ снимает (пара
/// снимает только нечётную, то есть линейную, часть). Без коррекции оценка
/// матрицы упирается в пол ~0.14 по форме.
///
/// ВАЖНО, чем поле мерить. Первая попытка — фитить поле по НЕВЯЗКЕ самих
/// плиток — провалилась (ошибка выросла 0.120 -> 0.140): при точечной симметрии
/// обе копии класса лежат на ОДНОМ радиусе, поэтому «цвет» и «радиус»
/// коррелированы ПОЛНОСТЬЮ, и полином поля начинает объяснять цветовые ошибки.
/// Поле неотличимо от цвета — по построению раскладки. Поэтому зонд поля — РОВ:
/// средне-серый, ОДИН И ТОТ ЖЕ цвет вокруг каждой плитки, замеряемый в её
/// собственном месте. Цвет фиксирован -> смешения с цветом нет по построению.
const FIELD_TERMS: usize = 6;

#[inline]
fn field_basis(x: f64, y: f64) -> [f64; FIELD_TERMS] {
    [1.0, x, y, x * x, y * y, x * y]
}

/// Гаусс с частичным выбором ведущего для малой плотной системы.
fn solve_dense(a: &mut [[f64; FIELD_TERMS]; FIELD_TERMS], b: &mut [f64; FIELD_TERMS]) -> bool {
    let scale = (0..FIELD_TERMS).fold(0.0f64, |m, i| m.max(a[i][i].abs()));
    if scale <= 0.0 {
        return false;
    }
    for col in 0..FIELD_TERMS {
        let mut piv = col;
        for r in col + 1..FIELD_TERMS {
            if a[r][col].abs() > a[piv][col].abs() {
                piv = r;
            }
        }
        if a[piv][col].abs() < 1e-12 * scale {
            return false;
        }
        a.swap(col, piv);
        b.swap(col, piv);
        let d = a[col][col];
        for j in col..FIELD_TERMS {
            a[col][j] /= d;
        }
        b[col] /= d;
        for r in 0..FIELD_TERMS {
            if r != col {
                let f = a[r][col];
                if f != 0.0 {
                    for j in col..FIELD_TERMS {
                        a[r][j] -= f * a[col][j];
                    }
                    b[r] -= f * b[col];
                }
            }
        }
    }
    b.iter().all(|v| v.is_finite())
}

/// Взвешенный МНК био-квадратичного поля по точкам `(x, y, значение, вес)`.
/// `None` — точек/обусловленности не хватило.
fn fit_field(pts: &[(f64, f64, f64, f64)]) -> Option<[f64; FIELD_TERMS]> {
    if pts.len() < FIELD_TERMS + 2 {
        return None;
    }
    let mut a = [[0.0f64; FIELD_TERMS]; FIELD_TERMS];
    let mut b = [0.0f64; FIELD_TERMS];
    for &(x, y, v, w) in pts {
        if w <= 0.0 || !v.is_finite() {
            continue;
        }
        let f = field_basis(x, y);
        for i in 0..FIELD_TERMS {
            b[i] += w * f[i] * v;
            for j in 0..FIELD_TERMS {
                a[i][j] += w * f[i] * f[j];
            }
        }
    }
    if solve_dense(&mut a, &mut b) {
        Some(b)
    } else {
        None
    }
}

#[inline]
fn field_at(c: &[f64; FIELD_TERMS], x: f64, y: f64) -> f64 {
    let f = field_basis(x, y);
    (0..FIELD_TERMS).map(|i| c[i] * f[i]).sum()
}

/// Средние сырые RGB по РВУ слева и справа от каждой плитки — прямой зонд поля
/// освещённости в месте плитки. Берутся ДАЛЬНИЕ столбцы рва (в 1 клетке от тела
/// плитки), поэтому краевой блюр тела в них практически не доходит; по
/// вертикали ров всего 1 клетка, и он не используется.
fn moat_means(
    p: &CalibProfile,
    map: &dyn Fn(f64, f64) -> (f64, f64),
    sample: &dyn Fn(f64, f64) -> [f32; 3],
) -> [[f64; 3]; TILES] {
    let mut out = [[0.0f64; 3]; TILES];
    for (slot, o) in out.iter_mut().enumerate() {
        let (c0, r0, cw, rh) = tile_rect(slot);
        if cw == 0 || rh == 0 {
            continue;
        }
        let left = c0.saturating_sub(GUARD_COLS);
        let right = (c0 + cw + GUARD_COLS - 1).min(PAYLOAD_COLS - 1);
        let mut acc = [0.0f64; 3];
        let mut cnt = 0.0f64;
        for pr in r0..r0 + rh {
            for pc in [left, right] {
                let s = cell_rgb(p, pc, pr, map, sample);
                for c in 0..3 {
                    acc[c] += s[c];
                }
                cnt += 1.0;
            }
        }
        if cnt > 0.0 {
            for c in 0..3 {
                o[c] = acc[c] / cnt;
            }
        }
    }
    out
}

/// МНК `t̂ = N·s + q` по набору пар (сырой линеаризованный `s`, истинный `t`).
fn fit_matrix(pts: &[([f64; 3], [f64; 3])]) -> Option<ChannelMatrix> {
    let mut ata = [[0.0f64; 4]; 4];
    let mut atb = [[0.0f64; 3]; 4];
    for (s, t) in pts {
        let basis = [s[0], s[1], s[2], 1.0];
        for i in 0..4 {
            for c in 0..3 {
                atb[i][c] += basis[i] * t[c];
            }
            for j in 0..4 {
                ata[i][j] += basis[i] * basis[j];
            }
        }
    }
    symbol::solve4x3(&ata, &atb).map(|(n, q)| ChannelMatrix { n, q })
}

/// Контраст Мишельсона решётки зонда блюра, по полосам шага.
///
/// Возвращает `[(1/p², ln C)]` — готовые точки лог-линейного фита; полосы с
/// вырожденным или зашкалившим контрастом отброшены.
fn blur_points(
    p: &CalibProfile,
    slot: usize,
    gammas: &[f64; 3],
    map: &dyn Fn(f64, f64) -> (f64, f64),
    sample: &dyn Fn(f64, f64) -> [f32; 3],
) -> Vec<(f64, f64)> {
    let quiet = p.quiet_zone_cells() as usize;
    let cell = p.cell_size_px as usize;
    let (pc0, pr0, cols, rows) = tile_rect(slot);
    let mut out = Vec::new();
    if cols == 0 || rows == 0 {
        return out;
    }
    let bx0 = ((quiet + RING + pc0) * cell) as f64;
    let by0 = ((quiet + RING + 1 + pr0) * cell) as f64;
    let bw = cols * cell;
    let bh = rows * cell;
    let m = cell; // отступ 1 клетка от края тела (краевой блюр от рва)
    let orient_x = blur_orient_x(slot);
    let pitches = blur_pitches(cell);
    // яркость: линеаризованный зелёный (зонд нейтрален -> хрома не участвует)
    let lum = |x: f64, y: f64| -> f64 {
        let s = sample(x, y);
        (s[1].max(0.0) as f64).powf(gammas[1])
    };

    for (band, &pitch) in pitches.iter().enumerate() {
        // диапазон полосы по «поперечной» оси
        let (cross_lo, cross_hi, cross_len) = if orient_x {
            (band * bh / 3, (band + 1) * bh / 3, bh)
        } else {
            (band * bw / 3, (band + 1) * bw / 3, bw)
        };
        let lo = cross_lo.max(m);
        let hi = cross_hi.min(cross_len.saturating_sub(m));
        if hi <= lo {
            continue;
        }
        // 5 позиций поперёк полосы
        const NCROSS: usize = 5;
        let along_len = if orient_x { bw } else { bh };
        let (mut sw, mut sb, mut nw, mut nb) = (0.0f64, 0.0f64, 0.0f64, 0.0f64);
        for ci in 0..NCROSS {
            let cpos = lo as f64 + (ci as f64 + 0.5) * (hi - lo) as f64 / NCROSS as f64;
            let mut k = 0usize;
            while (k + 1) * pitch <= along_len {
                let xb = (k * pitch + pitch / 4) as f64;
                let xw = (k * pitch + 3 * pitch / 4) as f64;
                for (a, is_white) in [(xb, false), (xw, true)] {
                    if a < m as f64 || a > (along_len - m) as f64 {
                        continue;
                    }
                    let (u, v) = if orient_x {
                        (bx0 + a, by0 + cpos)
                    } else {
                        (bx0 + cpos, by0 + a)
                    };
                    let (x, y) = map(u, v);
                    let l = lum(x, y);
                    if is_white {
                        sw += l;
                        nw += 1.0;
                    } else {
                        sb += l;
                        nb += 1.0;
                    }
                }
                k += 1;
            }
        }
        if nw < 1.0 || nb < 1.0 {
            continue;
        }
        let (iw, ib) = (sw / nw, sb / nb);
        let denom = iw + ib;
        if denom.abs() < 1e-12 {
            continue;
        }
        let c = ((iw - ib) / denom).clamp(0.0, 0.9995);
        // за пределами окна точка либо утонула в шуме, либо упёрлась в потолок
        // (контраст ~1 не несёт информации о наклоне ln C по 1/p²)
        if !(0.01..=0.995).contains(&c) {
            continue;
        }
        let inv_p2 = 1.0 / (pitch as f64 * pitch as f64);
        out.push((inv_p2, c.ln()));
    }
    out
}

/// σ из точек `(1/p², ln C)` лог-линейной регрессией (§4-IB, см. док. модуля).
fn sigma_from_points(pts: &[(f64, f64)]) -> Option<f64> {
    if pts.len() < 2 {
        return None;
    }
    let n = pts.len() as f64;
    let sx: f64 = pts.iter().map(|q| q.0).sum();
    let sy: f64 = pts.iter().map(|q| q.1).sum();
    let sxx: f64 = pts.iter().map(|q| q.0 * q.0).sum();
    let sxy: f64 = pts.iter().map(|q| q.0 * q.1).sum();
    let den = n * sxx - sx * sx;
    if den.abs() < 1e-24 {
        return None;
    }
    let slope = (n * sxy - sx * sy) / den;
    if slope >= 0.0 {
        return Some(0.0); // контраст не падает с частотой — блюра нет
    }
    let tau = core::f64::consts::PI * core::f64::consts::PI * 2.0;
    Some((-slope / tau).max(0.0).sqrt())
}

/// Оценка канала по внутриполосному калибровочному кадру (§4-IB.4).
///
/// `sample` отдаёт СЫРОЙ (до гаммы) нормированный RGB снимка — те же соглашения,
/// что у [`crate::tone::estimate_channel_gammas`]. Порядок операций:
/// 1. средние по 24 плиткам -> усреднение точечно-симметричных пар (поле снято);
/// 2. гамма линеаризации по нейтральной лесенке из 5 КРУПНЫХ плиток —
///    [`crate::tone::fit_linearisation_gamma`], тот же оценщик, что по §3.4;
/// 3. матрица 3×3 + смещение МНК по 11 сплошным классам;
/// 4. σ блюра из контраста решётки (см. док. модуля);
/// 5. контрольные величины: невязка фита и расхождение половин кадра.
pub fn estimate_from_frame(
    p: &CalibProfile,
    map: &dyn Fn(f64, f64) -> (f64, f64),
    sample: &dyn Fn(f64, f64) -> [f32; 3],
) -> CalibEstimate {
    let mut est = CalibEstimate::degenerate();
    est.marker_rho = marker_score(p, map, sample);
    est.uniformity = tile_uniformity(p, map, sample);

    let (k, w) = symbol::levels(p);
    let raw = tile_means(p, map, sample);
    let gprof = [p.gamma_r() as f64, p.gamma_g() as f64, p.gamma_b() as f64];

    // --- 1. наблюдения ПО ПЛИТКАМ (сплошные), плюс их позиции в кадре ---
    struct Obs {
        slot: usize,
        raw: [f64; 3],
        t: [f64; 3],
        x: f64,
        y: f64,
    }
    let mut obs: Vec<Obs> = Vec::with_capacity(TILES);
    for slot in 0..TILES {
        let cls = slot_class(slot);
        let drive = match class_drive(cls, k, w) {
            Some(d) => d,
            None => continue,
        };
        let mut t = [0.0f64; 3];
        for c in 0..3 {
            t[c] = (drive[c] as f64 / 255.0).powf(gprof[c]);
        }
        let (x, y) = tile_centre_norm(slot);
        obs.push(Obs {
            slot,
            raw: raw[slot],
            t,
            x,
            y,
        });
    }
    if obs.len() < 8 {
        return est;
    }

    // --- 2. первичная гамма: точечно-симметрично усреднённая лесенка ---
    // Усреднение пары снимает НЕЧЁТНУЮ (линейную) часть поля точно; чётная
    // часть уйдёт на шаге 3 вместе с полиномом поля.
    let mut lam = vec![1.0f64; obs.len()];
    let stair_raw = |lam: &[f64], gam: &[f64; 3]| -> Vec<(f64, [f64; 3])> {
        let mut lv: Vec<(f64, [f64; 3])> = STAIRCASE
            .iter()
            .map(|&(cls, f)| {
                let d = (k as f64 + (w as f64 - k as f64) * f) / 255.0;
                let mut acc = [0.0f64; 3];
                let mut n = 0.0f64;
                for (i, o) in obs.iter().enumerate() {
                    if slot_class(o.slot) != cls {
                        continue;
                    }
                    // поле снимается в ЛИНЕЙНОМ домене: raw' = λ^(1/γ)·raw
                    for c in 0..3 {
                        acc[c] += o.raw[c] * lam[i].max(1e-9).powf(1.0 / gam[c]);
                    }
                    n += 1.0;
                }
                if n > 0.0 {
                    for c in 0..3 {
                        acc[c] /= n;
                    }
                }
                (d, acc)
            })
            .collect();
        lv.sort_by(|a, b| a.0.partial_cmp(&b.0).unwrap_or(core::cmp::Ordering::Equal));
        lv
    };
    est.gammas = tone::fit_linearisation_gamma(&stair_raw(&lam, &[2.2; 3]), &gprof);

    // --- 3. чередование «матрица <-> поле <-> гамма» ---
    let lin = |s: [f64; 3], g: &[f64; 3]| -> [f64; 3] {
        [
            s[0].max(0.0).powf(g[0]),
            s[1].max(0.0).powf(g[1]),
            s[2].max(0.0).powf(g[2]),
        ]
    };
    let points = |lam: &[f64], gam: &[f64; 3]| -> Vec<([f64; 3], [f64; 3])> {
        obs.iter()
            .enumerate()
            .map(|(i, o)| {
                let s = lin(o.raw, gam);
                ([s[0] * lam[i], s[1] * lam[i], s[2] * lam[i]], o.t)
            })
            .collect()
    };

    let mut m = match fit_matrix(&points(&lam, &est.gammas)) {
        Some(m) => m,
        None => return est,
    };
    // Зонд поля — ров: ОДИН И ТОТ ЖЕ средне-серый вокруг каждой плитки.
    let moat = moat_means(p, map, sample);
    let t_moat = {
        let d = 128.0f64 / 255.0;
        [d.powf(gprof[0]), d.powf(gprof[1]), d.powf(gprof[2])]
    };
    for _ in 0..2 {
        // 3a. поле в месте плитки: t̂_ров = N·s_ров + q ≈ (f_i/f̄)·t_серый,
        //     значит δ_i = ⟨t̂, t⟩/⟨t̂, t̂⟩ = f̄/f_i. Цвет зонда ФИКСИРОВАН,
        //     поэтому с цветом плитки эта величина не смешивается.
        let mut fp: Vec<(f64, f64, f64, f64)> = Vec::with_capacity(obs.len());
        for (i, o) in obs.iter().enumerate() {
            let s = lin(moat[o.slot], &est.gammas);
            let h = m.apply([s[0] * lam[i], s[1] * lam[i], s[2] * lam[i]]);
            let hh: f64 = h.iter().map(|v| v * v).sum();
            if hh <= 1e-12 {
                continue;
            }
            let ht: f64 = (0..3).map(|c| h[c] * t_moat[c]).sum();
            fp.push((o.x, o.y, ht / hh, hh));
        }
        // 3b. сглаживаем био-квадратикой и нормируем к среднему 1 (общий
        //     масштаб безвреден — он уходит в матрицу, см. shape_rel_error)
        let coef = match fit_field(&fp) {
            Some(c) => c,
            None => break,
        };
        let vals: Vec<f64> = obs.iter().map(|o| field_at(&coef, o.x, o.y)).collect();
        let mean: f64 = vals.iter().sum::<f64>() / vals.len() as f64;
        if !(mean.is_finite() && mean.abs() > 1e-9) {
            break;
        }
        let (mut lo, mut hi) = (f64::INFINITY, f64::NEG_INFINITY);
        for (i, v) in vals.iter().enumerate() {
            lam[i] *= (v / mean).clamp(0.25, 4.0);
            lo = lo.min(lam[i]);
            hi = hi.max(lam[i]);
        }
        est.field_lo = lo;
        est.field_hi = hi;
        // 3c. гамма по лесенке, скорректированной полем; затем матрица заново
        est.gammas = tone::fit_linearisation_gamma(&stair_raw(&lam, &est.gammas), &gprof);
        m = match fit_matrix(&points(&lam, &est.gammas)) {
            Some(m) => m,
            None => break,
        };
    }
    est.matrix = m;
    est.ok = true;

    // невязка фита: СКО |t̂ − t| по плиткам
    let pts = points(&lam, &est.gammas);
    let mut sse = 0.0;
    for (s, t) in &pts {
        let th = m.apply(*s);
        for c in 0..3 {
            let e = th[c] - t[c];
            sse += e * e;
        }
    }
    est.residual = (sse / (pts.len() * 3) as f64).sqrt();

    // пространственная изменчивость канала: матрица верхней половины кадра
    // против нижней. Классы в половинах ОДНИ И ТЕ ЖЕ (точечная симметрия),
    // поэтому расхождение — свойство канала, а не разных наборов цветов.
    let mut top = Vec::with_capacity(obs.len());
    let mut bot = Vec::with_capacity(obs.len());
    for (i, o) in obs.iter().enumerate() {
        if o.slot < TILES / 2 {
            top.push(pts[i]);
        } else {
            bot.push(pts[i]);
        }
    }
    est.spatial_spread = match (fit_matrix(&top), fit_matrix(&bot)) {
        (Some(a), Some(b)) => a.shape_rel_error(&b),
        _ => f64::INFINITY,
    };

    // --- 4. σ блюра ---
    let bx = class_slot(CLASS_BLUR);
    let by = partner_slot(bx);
    let (sx, sy) = if blur_orient_x(bx) { (bx, by) } else { (by, bx) };
    est.sigma_x_px = sigma_from_points(&blur_points(p, sx, &est.gammas, map, sample)).unwrap_or(0.0);
    est.sigma_y_px = sigma_from_points(&blur_points(p, sy, &est.gammas, map, sample)).unwrap_or(0.0);
    est.sigma_px = (0.5 * (est.sigma_x_px * est.sigma_x_px + est.sigma_y_px * est.sigma_y_px)).sqrt();

    // --- 5. ядро межклеточной интерференции ---
    // Кадр известен ЦЕЛИКОМ, поэтому фит не решение-направленный: у него нет
    // области сходимости, и он одинаково работает при любой SER полезной
    // нагрузки. Матрица развязки берётся ТОЛЬКО ЧТО оценённая — ядро живёт в
    // светолинейной величине `t = N·s + q` и без развязки было бы смешано с
    // перекрёстными наводками каналов.
    if est.ok {
        let ideal = calib_ideal_drives(p, counter_of(p, map, sample));
        est.isi = symbol::estimate_isi_known_frame(
            p,
            map,
            sample,
            Some(&est.matrix),
            &ideal,
            Some(&calib_kernel_mask()),
            &IsiConfig::default(),
        );
    }
    est
}

/// Младшие 8 бит номера кадра из строки счётчика §3.3 (первая копия).
///
/// Калибровочный кадр несёт счётчик наравне с payload-кадром, а строка счётчика
/// входит в сетку идеальных драйвов — без верного счётчика 16 её клеток были бы
/// заданы неверно и слегка испортили бы фит.
fn counter_of(
    p: &CalibProfile,
    map: &dyn Fn(f64, f64) -> (f64, f64),
    sample: &dyn Fn(f64, f64) -> [f32; 3],
) -> u8 {
    symbol::read_counters(p, map, sample).0
}

// ---------------------------------------------------------------------------
// Приёмник: кэш калибровки и проверка на устаревание (§4-IB.4)
