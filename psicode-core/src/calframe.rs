/// Высота маркерной полосы в payload-строках (§4-IB.2).
pub const MARKER_ROWS: usize = 3;
/// Корень ЗЧ маркерной последовательности. 1..4 заняты кольцом §3.2.
pub const MARKER_ROOT: u32 = 5;
/// Столбцов плиток.
pub const TILE_COLS: usize = 4;
/// Строк плиток.
pub const TILE_ROWS: usize = 6;
/// Всего плиток.
pub const TILES: usize = TILE_COLS * TILE_ROWS;
/// Классов патчей (= TILES / 2, точечно-симметричные пары).
pub const CLASSES: usize = TILES / 2;
/// Ров между плитками по X, в клетках с каждой стороны (48 px между телами).
pub const GUARD_COLS: usize = 2;
/// Ров между плитками по Y, в клетках с каждой стороны (24 px между телами).
pub const GUARD_ROWS: usize = 1;
/// Отступ внутрь тела плитки при ИЗМЕРЕНИИ (клетки): край тела не читаем.
pub const READ_MARGIN: usize = 1;
/// Строк payload под маркерной полосой (сетка плиток).
const BAND_ROWS: usize = PAYLOAD_ROWS - MARKER_ROWS;
/// Столбцов payload под сеткой плиток. РОВНО 56, а не все 57: точечная
/// симметрия требует, чтобы границы удовлетворяли `e_i + e_{K−i} = N`, а при
/// нечётном `N` и чётном числе плиток это невозможно (средняя граница обязана
/// была бы лечь на полклетки). Лишний 57-й столбец остаётся рвом — заодно
/// правой крайней плитке достаётся ров в 3 клетки вместо 2.
const GRID_COLS: usize = PAYLOAD_COLS - 1;

/// Порог корреляции маркера (§4-IB.2). 0.60 = 4.5 sd нуль-гипотезы (1/√57).
pub const MARKER_RHO_MIN: f64 = 0.60;
/// Порог однородности плиток (§4-IB.2).
pub const UNIFORMITY_MIN: f64 = 0.50;

