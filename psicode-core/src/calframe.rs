/// Максимальный возраст кэша в кадрах: два установившихся интервала. Дольше
/// ждать нечего — следующий калибровочный кадр гарантированно уже прошёл, а
/// значит его пропустили и надо считать калибровку недействительной.
pub const CALIB_MAX_AGE: u64 = 2 * CALIB_PERIOD;
/// Порог здоровья декодирования (доля CRC-валидных страйпов), ниже которого
/// кэш считается устаревшим и приёмник ЖДЁТ следующего калибровочного кадра.
/// Обратного канала нет — ничего не запрашивается, просто ре-синхронизация.
pub const CALIB_HEALTH_MIN: f64 = 0.35;
/// Постоянная EWMA здоровья (доля нового кадра в оценке).
pub const CALIB_HEALTH_ALPHA: f64 = 0.2;

/// Кэш калибровки приёмника с контролем устаревания (§4-IB.4).
#[derive(Debug, Clone, Copy)]
pub struct CalibCache {
    est: Option<CalibEstimate>,
    age: u64,
    health: f64,
}

impl Default for CalibCache {
    fn default() -> Self {
        Self::new()
    }
}

impl CalibCache {
    /// Пустой кэш: калибровки нет, здоровье «идеальное» (нечему деградировать).
    pub fn new() -> Self {
        CalibCache {
            est: None,
            age: 0,
            health: 1.0,
        }
    }

    /// Принять новую оценку с калибровочного кадра.
    pub fn accept(&mut self, est: CalibEstimate) {
        if est.ok {
            self.est = Some(est);
            self.age = 0;
            self.health = 1.0;
        }
    }

    /// Учесть очередной payload-кадр: возраст +1, здоровье — EWMA доли
    /// CRC-валидных страйпов.
    pub fn observe_payload(&mut self, stripes_ok: u8, stripes_total: u8) {
        self.age = self.age.saturating_add(1);
        if stripes_total > 0 {
            let q = stripes_ok as f64 / stripes_total as f64;
            self.health = (1.0 - CALIB_HEALTH_ALPHA) * self.health + CALIB_HEALTH_ALPHA * q;
        }
    }

    /// Возраст кэша в кадрах.
    pub fn age(&self) -> u64 {
        self.age
    }

    /// Текущая оценка здоровья декодирования (EWMA).
    pub fn health(&self) -> f64 {
        self.health
    }

    /// Устарел ли кэш. Устаревание — не запрос, а решение ЖДАТЬ следующего
    /// запланированного калибровочного кадра: обратного канала нет.
    pub fn stale(&self) -> bool {
        self.est.is_none() || self.age > CALIB_MAX_AGE || self.health < CALIB_HEALTH_MIN
    }

    /// Действующая калибровка (`None`, если её нет или она устарела).
    pub fn get(&self) -> Option<&CalibEstimate> {
        if self.stale() {
            None
        } else {
            self.est.as_ref()
        }
    }

    /// Последняя принятая оценка, невзирая на устаревание (диагностика).
    pub fn last(&self) -> Option<&CalibEstimate> {
        self.est.as_ref()
    }
}

