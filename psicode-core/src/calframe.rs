/// Корреляция маркерной полосы (§4-IB.2), `[-1, 1]`.
///
/// Наблюдаемая — вторая разность по вертикали `d(n) = ½(L₀+L₂) − L₁` по
/// зелёному каналу: линейное по y поле она обнуляет ТОЖДЕСТВЕННО, кривизну
/// сводит к константе (снимается вычитанием среднего). Порог монотонен, поэтому
/// `sample` может быть и сырым, и линеаризованным.
pub fn marker_score(
    p: &CalibProfile,
    map: &dyn Fn(f64, f64) -> (f64, f64),
    sample: &dyn Fn(f64, f64) -> [f32; 3],
) -> f64 {
    let n = PAYLOAD_COLS;
    let mut d = vec![0.0f64; n];
    let mut s = vec![0.0f64; n];
    for (pc, (dv, sv)) in d.iter_mut().zip(s.iter_mut()).enumerate() {
        let l0 = cell_green(p, pc, 0, map, sample);
        let l1 = cell_green(p, pc, 1, map, sample);
        let l2 = cell_green(p, pc, 2, map, sample);
        *dv = 0.5 * (l0 + l2) - l1;
        *sv = if zc_binary(MARKER_ROOT, pc) { 1.0 } else { -1.0 };
    }
    let dm = d.iter().sum::<f64>() / n as f64;
    let sm = s.iter().sum::<f64>() / n as f64;
    let (mut num, mut dd, mut ss) = (0.0f64, 0.0f64, 0.0f64);
    for i in 0..n {
        let a = d[i] - dm;
        let b = s[i] - sm;
        num += a * b;
        dd += a * a;
        ss += b * b;
    }
    if dd <= 1e-18 || ss <= 1e-18 {
        0.0
    } else {
        num / (dd.sqrt() * ss.sqrt())
    }
}

/// Однородность плиток (§4-IB.2): `1 − ⟨дисперсия ВНУТРИ плитки⟩ / дисперсия
/// средних МЕЖДУ плитками`, по зелёному каналу и только по сплошным плиткам.
///
/// У калибровочного кадра ≈ 0.999 (внутри плитки только шум), у payload-кадра
/// резко отрицательна (внутриплиточная дисперсия случайных данных на порядки
/// больше межплиточной). Независимый от маркера признак.
pub fn tile_uniformity(
    p: &CalibProfile,
    map: &dyn Fn(f64, f64) -> (f64, f64),
    sample: &dyn Fn(f64, f64) -> [f32; 3],
) -> f64 {
    let mut means = Vec::with_capacity(TILES);
    let mut within = 0.0f64;
    let mut nt = 0.0f64;
    for slot in 0..TILES {
        if slot_class(slot) == CLASS_BLUR {
            continue; // решётка неоднородна ПО ЗАМЫСЛУ
        }
        let (c0, r0, cw, rh) = tile_read_rect(slot);
        if cw == 0 || rh == 0 {
            continue;
        }
        let (mut sum, mut sumsq, mut cnt) = (0.0f64, 0.0f64, 0.0f64);
        for pr in r0..r0 + rh {
            for pc in c0..c0 + cw {
                let g = cell_green(p, pc, pr, map, sample);
                sum += g;
                sumsq += g * g;
                cnt += 1.0;
            }
        }
        if cnt < 2.0 {
            continue;
        }
        let m = sum / cnt;
        within += (sumsq / cnt - m * m).max(0.0);
        nt += 1.0;
        means.push(m);
    }
    if nt < 2.0 || means.len() < 2 {
        return 0.0;
    }
    within /= nt;
    let mm = means.iter().sum::<f64>() / means.len() as f64;
    let between =
        means.iter().map(|m| (m - mm) * (m - mm)).sum::<f64>() / means.len() as f64;
    if between <= 1e-12 {
        return -1e6;
    }
    1.0 - within / between
}

/// Признак калибровочного кадра: маркер И однородность плиток (§4-IB.2).
pub fn is_calibration_frame(
    p: &CalibProfile,
    map: &dyn Fn(f64, f64) -> (f64, f64),
    sample: &dyn Fn(f64, f64) -> [f32; 3],
) -> bool {
    marker_score(p, map, sample) >= MARKER_RHO_MIN
        && tile_uniformity(p, map, sample) >= UNIFORMITY_MIN
}

