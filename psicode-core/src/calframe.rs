//! ВНУТРИПОЛОСНЫЕ КАЛИБРОВОЧНЫЕ КАДРЫ (амендмент к §4; далее §4-IB).
//!
//! Целые кадры, вплетённые в поток данных, которые несут калибровку канала.
//! Геометрия символа — ШТАТНАЯ (тихая зона, двойное ЗЧ-кольцо §3.2, референсная
//! строка §3.4, строка счётчика §3.3), поэтому детекция, гомография и трекинг
//! приёмника работают без единой правки. Меняется только СОДЕРЖИМОЕ
//! payload-сетки 57×55.
//!
//! # Зачем: разделение труда по временнЫм масштабам
//!
//! Измерения этого проекта (см. `swatch.rs`, `psicode-sim gprobe`) разводят
//! величины канала на два семейства:
//!
//! * **редкие и глобальные** — матрица развязки каналов 3×3, пер-канальная
//!   гамма, σ блюра. Они зависят от пары «дисплей+камера» и от ЗАФИКСИРОВАННЫХ
//!   экспозиции и баланса белого, то есть меняются за секунды, а не за кадры.
//!   Их место — калибровочный кадр;
//! * **покадровые и бесплатные** — поле освещённости. Приёмник получает ~576
//!   зондов поля из САМИХ ДАННЫХ (payload-клетки нуль-среднее), и глобальный
//!   полиномиальный фит по поклеточным средним даёт 0.20–0.22 % остаточной
//!   ошибки поля — лучше, чем встроенные пилоты (0.75–1.82 %) и чем
//!   зарезервированный калибровочный канал (4.42 %). Поле в калибровочный кадр
//!   НЕ выносится.
//!
//! # Почему референсная строка §3.4 этого не может
//!
//! Строка ВЫСОТОЙ В ОДНУ КЛЕТКУ (12 px) — самый хрупкий пространственный
//! масштаб символа: НЧ-фильтр хромы ISP размазывает соседние цветные патчи друг
//! в друга раньше, чем портит что-либо ещё, и матрица 3×3, снятая с такой
//! строки, испорчена. На лестнице масштабов (`swatch.rs`) ТА ЖЕ матрица при
//! `n = 4` (блок 120 px) восстанавливает усиления осей до 1.023 / 1.120 и
//! убивает поворот (−0.44°), а на клеточном масштабе — нет. Само искажение
//! канала масштабно-НЕзависимо и линейно (сырые усиления осей Re 0.647 / 0.614 /
//! 0.534 и Im 0.819 / 0.900 / 0.757 при n = 1 / 4 / 16), значит лечится оно
//! именно матрицей — просто мерить её надо на КРУПНОМ масштабе.
//!
//! # Раскладка (payload-координаты, 57 столбцов × 55 строк)
//!
//! ```text
//! ┌───────────────────────────────────────────────────────┐
//! │ pr 0..2   МАРКЕРНАЯ ПОЛОСА: 57×3, бинарная, luma-only  │  самоидентификация
//! ├───────────────────────────────────────────────────────┤
//! │ pr 3..54  СЕТКА ПЛИТОК 4 столбца × 6 строк = 24 плитки │
//! │           = 12 КЛАССОВ × 2 точечно-симметричные копии   │
//! │   R  G  B  BL     (BL = зонд блюра, ориентация X)       │
//! │   C  K  g1 M                                           │
//! │   g3 Y  g2 W                                           │
//! │   W  g2 Y  g3     <- поворот верхней половины на 180°   │
//! │   M  g1 K  C                                           │
//! │   BL B  G  R      (BL = зонд блюра, ориентация Y)       │
//! └───────────────────────────────────────────────────────┘
//! ```
//!
//! Сетка занимает 56 из 57 столбцов payload: точечная симметрия требует
//! `граница(i) + граница(K−i) = N`, что при нечётном `N` невозможно. 57-й
//! столбец остаётся рвом.
//!
//! ## Размер патча: почему 120×72 px, а не 12×12 и не 600×600
//!
//! Плитка = 10 × 6–7 клеток тела (ров 2 клетки по X и 1 по Y снимается с
//! каждой стороны), при `cell = 12` это **120 × 72–84 display-px**;
//! ИЗМЕРЯЕТСЯ внутренняя часть с отступом ещё в 1 клетку — 96 × 48–60 px,
//! то есть до чужого цвета от края измеряемой области ≥ 36 px по X и ≥ 24 px
//! по Y. Замеренный на железе НЧ-фильтр хромы ISP имеет σ ≈ 3.4 px (12-px патч
//! сохраняет 0.84–0.87 хромы 120-px патча — лестница масштабов, усиление осей
//! Re 0.614 -> 0.534 и Im 0.900 -> 0.757 при n = 4 -> 16), то есть даже узкий
//! вертикальный зазор 24 px — это 7σ. Обоснование ровно эмпирическое: лестница масштабов даёт РАБОТАЕТ при
//! 120 px и НЕ РАБОТАЕТ при 12 px, промежуточных замеров у нас нет, поэтому
//! берём измеренно-хорошую точку, а не интерполяцию. Крупнее (n = 1, ~600 px)
//! тоже работает, но тогда в кадр влезает 1–4 патча, и ни матрицу по 11 цветам,
//! ни пространственную изменчивость измерить нечем.
//!
//! ## Точечно-симметричное размножение
//!
//! Класс плитки — `SLOT_CLASS[min(slot, 23 − slot)]`, то есть слоты `slot` и
//! `23 − slot` (а это ровно поворот на 180° вокруг центра сетки) несут ОДИН
//! класс. Среднее пары ТОЧНО снимает любое ЛИНЕЙНОЕ поле освещённости: точки
//! пары симметричны относительно центра, и линейный член в среднем сокращается
//! тождественно. (Ранее было установлено, что наивный блок 4×4 портится именно
//! наклоном поля поперёк него.) Две копии одного класса стоят в РАЗНЫХ половинах
//! кадра, поэтому по ним же измеряется и ПРОСТРАНСТВЕННАЯ изменчивость матрицы:
//! [`estimate_from_frame`] считает матрицу отдельно по верхней и нижней половине
//! и отдаёт их расхождение ([`CalibEstimate::spatial_spread`]).
//!
//! Компромисс, который здесь сознательно принят: пара (2 позиции) снимает
//! линейное поле точно, но не снимает перекрёстный квадратичный член `xy` —
//! для этого нужна четвёрка. Четвёрка при сохранении масштаба патча оставила бы
//! 6 классов вместо 12, чего не хватает ни на матрицу, ни на лесенку. 12 пар,
//! разбросанных по кадру, усредняют остаточную квадратику по разным `(a, b)`.
//!
//! ## Нейтральная лесенка (гамма)
//!
//! Классы `K, g1, g2, g3, W` — 5 равномерных уровней от `black_level` до
//! `white_level`, каждый на плитке того же крупного масштаба. Гамма считается
//! ТЕМ ЖЕ оценщиком, что и по референсной строке
//! ([`crate::tone::fit_linearisation_gamma`]) — меняется только источник точек.
//!
//! ## Зонд блюра и почему он НЕ путается с полем
//!
//! `gprobe` нашёл ловушку: кривизна поля и дефокус алиасятся в подпространстве
//! низких ЧЁТНЫХ мод, поэтому зонд из гладких чётно-симметричных признаков
//! читает поле вместо блюра. Здесь наблюдаемая — **контраст Мишельсона
//! бинарной решётки** `C = (I⁺ − I⁻)/(I⁺ + I⁻)`, снимаемый по парам отсчётов,
//! отстоящих на ПОЛПЕРИОДА (6–24 px). Для гладкого мультипликативного поля λ:
//! `C' = (λI⁺ − λI⁻)/(λI⁺ + λI⁻) = C` — поле сокращается ТОЧНО (с точностью до
//! изменения λ на полпериоде, а это ~0.3 % при замеренном размахе 0.62→0.86 по
//! всему кадру). Аддитивная вуаль `b` даёт `C' = C·(I⁺+I⁻)/(I⁺+I⁻+2b)` —
//! множитель, ОДИНАКОВЫЙ для всех шагов решётки, и он поглощается свободным
//! членом фита. Поэтому σ берётся из НАКЛОНА `ln C` по `1/p²`, а не из уровня:
//! ```text
//! ln C(p) = ln C₀ − 2π²σ²/p²      ->      σ = sqrt(−slope / (2π²))
//! ```
//! Три шага решётки `p ∈ {2·cell, cell, cell/2}` на плитку, две ортогональные
//! ориентации (плитка X и её точечно-симметричная пара — Y), поэтому меряются
//! σx и σy раздельно: 4:2:0 и rolling shutter анизотропны.
//!
//! # Самоидентификация (§4-IB.2)
//!
//! Приёмник обязан узнать калибровочный кадр ДО того, как сможет что-либо
//! декодировать, поэтому признак не может ехать в CRC-защищённом FrameHeader
//! (тому нужен уже откалиброванный канал). Маркер построен на единственном
//! режиме, доказанном на живом железе (им прошла первая байт-точная передача
//! файла): КРУПНЫЙ, БИНАРНЫЙ, ТОЛЬКО ЯРКОСТЬ.
//!
//! Три строки payload `pr = 0,1,2` несут `m`, `¬m`, `m`, где
//! `m(n) = zc_binary(5, n)` — бинаризованная ЗЧ-последовательность корня 5
//! (корни 1..4 заняты кольцом §3.2). Наблюдаемая — ВТОРАЯ РАЗНОСТЬ по вертикали
//! `d(n) = ½(L₀+L₂) − L₁`, которая тождественно обнуляет любое линейное по y
//! поле, а кривизну сводит к общей константе (снимается вычитанием среднего).
//! Решение — нормированная корреляция `ρ` вектора `d` с известным `±1`-шаблоном.
//!
//! Запас детекции: на payload-кадре те же клетки несут L3-данные, `ρ` ~
//! `N(0, 1/√57)`, sd = 0.132; порог [`MARKER_RHO_MIN`] = 0.60 — это 4.5 sd.
//! Дополнительно требуется ОДНОРОДНОСТЬ плиток [`tile_uniformity`] ≥
//! [`UNIFORMITY_MIN`]: у калибровочного кадра ~0.999, у payload-кадра резко
//! отрицательна (внутриплиточная дисперсия у случайных данных на 2–3 порядка
//! больше межплиточной). Два независимых признака И-логикой.
//!
//! # Расписание (§4-IB.3)
//!
//! Кадры 0, 1, 2, 4, 8, 16, 32, 64, 128, далее каждые 128
//! ([`is_calibration_index`]). Удвоение означает, что подключившийся поздно
//! приёмник ждёт не дольше ~удвоенного текущего интервала, а установившиеся
//! накладные расходы — 1/128 = 0.781 %.

